#!/bin/sh
#
# Generate the NTS PHP base Dockerfile from the docker-library recipe.
#
# Usage: generate.sh DOCKER_LIBRARY_PHP_CHECKOUT PHP_BRANCH
#
# From PHP 8.6 the official php images are thread-safe (ZTS) only.  The
# FreeUnit "php-<branch>" image stays non-thread-safe (NTS), like the images
# of PHP 8.5 and older, so FreeUnit builds its own NTS base: the cli
# Dockerfile of https://github.com/docker-library/php for Debian trixie,
# with the ZTS options removed.  Everything else (the PHP tarball and its
# GPG check, the extensions, the docker-php-ext-* helpers) is the same, so an
# image FROM the FreeUnit NTS base installs extensions as the official image
# does.
#
# The ZTS options of the recipe are "--enable-zts" and
# "--disable-zend-signals" with its comment line.  The script fails when the
# recipe no longer has them, so a changed recipe is seen and not copied by
# mistake.
#
# Example, after docker-library publishes a new 8.6 patch release:
#
#   git clone --depth 1 https://github.com/docker-library/php /tmp/dlphp
#   pkg/docker/php-nts/generate.sh /tmp/dlphp 8.6
#   cp /tmp/dlphp/docker-php-* pkg/docker/php-nts/

set -eu

[ $# -eq 2 ] || { echo "usage: $0 DOCKER_LIBRARY_PHP_CHECKOUT PHP_BRANCH" >&2; exit 2; }

src=$1/$2/trixie/cli/Dockerfile
out=$(dirname "$0")/Dockerfile.$2
commit=$(git -C "$1" rev-parse --short HEAD)

[ -r "$src" ] || { echo "$0: no $src" >&2; exit 1; }

# One extended regular expression per removed line.
zts_lines='^[[:space:]]*(--enable-zts|--disable-zend-signals)[[:space:]]+[\\]$|^# https://externals[.]io/message/118859$'

if [ "$(grep -cE "$zts_lines" "$src")" -ne 3 ]; then
    echo "$0: $src does not have the three ZTS lines this script removes" >&2
    exit 1
fi

{
    echo "# Generated by pkg/docker/php-nts/generate.sh from"
    echo "# https://github.com/docker-library/php/blob/$commit/$2/trixie/cli/Dockerfile"
    echo "# (MIT, see LICENSE in this directory) with the ZTS options removed:"
    echo "# PHP here is non-thread-safe (NTS).  Do not edit; run generate.sh."
    echo "#"
    grep -vE "$zts_lines" "$src"
} > "$out"

echo "$out: PHP $(sed -n 's/^ENV PHP_VERSION //p' "$out") NTS from docker-library $commit"
