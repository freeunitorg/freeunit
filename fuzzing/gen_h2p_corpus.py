def gen_rst_after_headers():
    conn = client()
    conn.send_headers(1, [
        (":method", "GET"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "/"),
    ])
    conn.reset_stream(1, error_code=8)  # CANCEL
    save("rst_after_headers.bin", strip_preface(conn.data_to_send()))


def gen_rst_before_headers_done():
    # RST_STREAM while the header block itself is mid-flight is not
    # something the h2 library will construct (it tracks stream state),
    # so build it by hand: HEADERS without END_HEADERS, then RST_STREAM.
    conn = client()
    conn.send_headers(1, [
        (":method", "GET"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "/"),
    ], end_stream=True)
    data = strip_preface(conn.data_to_send())
    data += raw_frame(0x3, 0x0, 1, struct.pack(">I", 0x8))
    save("rst_before_headers_done.bin", data)


def gen_settings_flood():
    conn = client()
    data = strip_preface(conn.data_to_send())
    # NXT_H2P_MAX_SETTINGS is 32; well past that, well under
    # NGHTTP2_ERR_TOO_MANY_SETTINGS's own bookkeeping cost.
    one = raw_frame(0x4, 0x0, 0, struct.pack(">HI", 4, 100))
    save("settings_flood.bin", data + one * 64)


