# --- malformed / hostile input, built by hand ---------------------------

def gen_bad_path_no_slash():
    # ":path" that is neither "/..." nor the OPTIONS-only "*":
    # nxt_h2p_request_target() answers 400.  h2 will not build a request
    # with this ":path" itself (it validates pseudo-headers), so the HEADERS
    # frame is HPACK-encoded here directly via hyperframe/hpack primitives
    # that h2 itself uses, bypassing only its request-line validation.
    import hpack

    encoder = hpack.Encoder()
    block = encoder.encode([
        (":method", "GET"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "not-a-path"),
    ])
    conn = client()
    preface = strip_preface(conn.data_to_send())
    frame = raw_frame(0x1, 0x5, 1, block)  # END_STREAM | END_HEADERS
    save("bad_path_no_slash.bin", preface + frame)


def gen_huge_header_field_name():
    # A field name over NXT_H2P_MAX_FIELD_NAME (255, nxt_http_field_t's
    # name_length is a uint8_t): the block is still consumed so HPACK state
    # stays in sync, but nxt_h2p_on_header() answers
    # NXT_HTTP_REQUEST_HEADER_FIELDS_TOO_LARGE instead of storing it.
    import hpack

    encoder = hpack.Encoder()
    block = encoder.encode([
        (":method", "GET"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "/"),
        ("x-" + "n" * 300, "v"),
    ])
    conn = client()
    preface = strip_preface(conn.data_to_send())
    frame = raw_frame(0x1, 0x5, 1, block)
    save("huge_header_field_name.bin", preface + frame)


def gen_header_list_too_large():
    # Enough fields, each within limits individually, to push
    # stream->header_list_size past large_header_buffer_size *
    # large_header_buffers -- the other branch of the same check.
    conn = client()
    headers = [
        (":method", "GET"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "/"),
    ]
    headers += [("x-bulk-%03d" % i, "v" * 200) for i in range(200)]
    conn.send_headers(1, headers, end_stream=True)
    save("header_list_too_large.bin", strip_preface(conn.data_to_send()))


def gen_garbage_after_valid_settings():
    # A well-formed SETTINGS frame followed by bytes that are not a valid
    # frame at all -- nghttp2_session_mem_recv() should fail the session
    # (NGHTTP2_ERR_*), driving nxt_h2p_conn_abort()'s error-code switch.
    conn = client()
    data = strip_preface(conn.data_to_send())
    save("garbage_after_settings.bin", data + b"\xff" * 32)


def gen_oversize_frame_header_only():
    # A frame header claiming a length far past SETTINGS_MAX_FRAME_SIZE
    # with no payload following: nghttp2 must reject this on the header
    # alone (a length lie), not read past the buffer.
    frame = struct.pack(">I", 0x00FFFFFF)[1:] + bytes([0x0, 0x0]) \
        + struct.pack(">I", 0)
    save("oversize_frame_header_only.bin", frame)


def gen_stream_id_zero_headers():
    # HEADERS on stream 0 is a connection error the h2 library also
    # refuses to build; hand-crafted like the other protocol violations.
    import hpack

