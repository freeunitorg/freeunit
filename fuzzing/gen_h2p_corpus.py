#!/usr/bin/env python3
#
# Generates fuzzing/fuzz_h2p_seed_corpus/ for fuzz_http_h2p.
#
# Requires the Python "h2" package: pip install --user h2
#
# fuzz_http_h2p's own harness (fuzzing/nxt_http_h2p_fuzz.c) always
# prepends the fixed 24-byte client connection preface before feeding a
# corpus file to nghttp2, exactly the way nxt_h2p_conn_init() expects it on
# the wire.  h2.connection.H2Connection.initiate_connection() writes that
# same preface into its own output, so every generator below strips it
# (see strip_preface()) before saving -- a seed file holds everything
# *after* the preface: the client's initial SETTINGS frame onward.
#
# Some seeds are built with the h2 library, which refuses to emit
# protocol violations; a handful of others below build raw frames by hand
# (raw_frame()) specifically to cover the malformed cases h2 will not
# produce: a bad pseudo-header path, a header list that blows past the
# server's advertised limit, and non-HPACK garbage.
#
# fuzz_h2p_seed_corpus/regress_stream_out_leak_on_conn_expire.bin is not
# generated by this script: it is a libFuzzer -minimize_crash artifact
# (a HEADERS(END_STREAM|END_HEADERS) request immediately followed by a
# client GOAWAY) that reproduces a real nxt_h2proto.c leak -- see the
# fuzzing session notes / PR description for the root cause -- and is
# committed as-is so the regression stays covered once fixed.

import os
import struct

import h2.connection
import h2.config

OUT_DIR = os.path.join(os.path.dirname(__file__), "fuzz_h2p_seed_corpus")

PREFACE = b"PRI * HTTP/2.0\r\n\r\nSM\r\n\r\n"


def strip_preface(data):
    assert data.startswith(PREFACE), "h2 did not emit the preface first"
    return data[len(PREFACE):]


def client():
    config = h2.config.H2Configuration(client_side=True)
    conn = h2.connection.H2Connection(config=config)
    conn.initiate_connection()
    return conn


def save(name, data):
    path = os.path.join(OUT_DIR, name)
    with open(path, "wb") as f:
        f.write(data)
    print("wrote %s (%d bytes)" % (path, len(data)))


def raw_frame(frame_type, flags, stream_id, payload):
    length = len(payload)
    return struct.pack(">I", length)[1:] + bytes([frame_type, flags]) \
        + struct.pack(">I", stream_id) + payload


# --- valid, ordinary requests -----------------------------------------

def gen_get():
    conn = client()
    conn.send_headers(1, [
        (":method", "GET"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "/"),
        ("user-agent", "fuzz-h2p/1.0"),
    ], end_stream=True)
    save("get.bin", strip_preface(conn.data_to_send()))


def gen_get_query_and_cookies():
    conn = client()
    conn.send_headers(1, [
        (":method", "GET"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "/search?q=fuzz&lang=en"),
        ("cookie", "a=1; b=2"),
        ("accept", "*/*"),
    ], end_stream=True)
    save("get_query_cookies.bin", strip_preface(conn.data_to_send()))


def gen_post_body():
    conn = client()
    conn.send_headers(1, [
        (":method", "POST"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "/upload"),
        ("content-type", "application/octet-stream"),
        ("content-length", "13"),
    ])
    conn.send_data(1, b"hello, world!", end_stream=True)
    save("post_body.bin", strip_preface(conn.data_to_send()))


def gen_post_body_no_content_length():
    # No content-length: nxt_h2p_request_headers_done() takes the chunked
    # (unknown length) body_alloc() path.
    conn = client()
    conn.send_headers(1, [
        (":method", "POST"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "/upload"),
    ])
    conn.send_data(1, b"a" * 256, end_stream=True)
    save("post_body_no_len.bin", strip_preface(conn.data_to_send()))


def gen_post_body_split_frames():
    # Same body, several DATA frames -- exercises the accounting in
    # nxt_h2p_on_data_chunk_recv() across more than one chunk.
    conn = client()
    conn.send_headers(1, [
        (":method", "POST"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "/upload"),
        ("content-length", "3000"),
    ])
    for _ in range(30):
        conn.send_data(1, b"x" * 100)
    conn.send_data(1, b"", end_stream=True)
    save("post_body_split.bin", strip_preface(conn.data_to_send()))


def gen_post_body_over_declared():
    # DATA adds up to more than the declared content-length; nghttp2 itself
    # is expected to catch this, but nxt_h2p_on_data_chunk_recv() has its
    # own belt-and-braces check (len > nxt_buf_mem_free_size()).
    conn = client()
    conn.send_headers(1, [
        (":method", "POST"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "/upload"),
        ("content-length", "4"),
    ])
    data = strip_preface(conn.data_to_send())
    # Hand-append a DATA frame with more bytes than declared; h2 would
    # refuse to build this itself.
    data += raw_frame(0x0, 0x1, 1, b"way too much data for four bytes")
    save("post_body_over_declared.bin", data)


def gen_put_trailers():
    conn = client()
    conn.send_headers(1, [
        (":method", "PUT"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "/x"),
        ("content-length", "5"),
    ])
    conn.send_data(1, b"hello")
    # Trailers: an extra HEADERS frame (HCAT_HEADERS), not HCAT_REQUEST;
    # nxt_h2p_request_end_stream() runs, the fields themselves are dropped.
    conn.send_headers(1, [("x-trailer", "done")], end_stream=True)
    save("put_trailers.bin", strip_preface(conn.data_to_send()))


def gen_options_star():
    # ":path" is "*", only legal for OPTIONS (RFC 9113, 8.3.1).
    conn = client()
    conn.send_headers(1, [
        (":method", "OPTIONS"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "*"),
    ], end_stream=True)
    save("options_star.bin", strip_preface(conn.data_to_send()))


def gen_dot_segment_path():
    # Exercises nxt_http_parse_complex_target()'s dot-segment normalization
    # by way of nxt_h2p_request_target().
    conn = client()
    conn.send_headers(1, [
        (":method", "GET"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "/a/../../b/./c%2e%2e/d"),
    ], end_stream=True)
    save("dot_segment_path.bin", strip_preface(conn.data_to_send()))


def gen_host_matches_authority():
    # A "host" field that agrees with ":authority": the fast-path compare
    # in nxt_h2p_on_header() (RFC 9113 8.3.1), not the mismatch error.
    conn = client()
    conn.send_headers(1, [
        (":method", "GET"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "/"),
        ("host", "example.com"),
    ], end_stream=True)
    save("host_matches_authority.bin", strip_preface(conn.data_to_send()))


def gen_host_mismatch():
    # "host" disagreeing with ":authority" (RFC 9113, 8.3.1) is a request
    # nxt_h2p_on_header() rejects (NGHTTP2_ERR_TEMPORAL_CALLBACK_FAILURE);
    # the h2 library validates this itself before send_headers() ever
    # builds a frame, so this goes through hpack directly, like the other
    # protocol violations below.
    import hpack

    encoder = hpack.Encoder()
    block = encoder.encode([
        (":method", "GET"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "/"),
        ("host", "evil.example"),
    ])
    conn = client()
    preface = strip_preface(conn.data_to_send())
    frame = raw_frame(0x1, 0x5, 1, block)
    save("host_mismatch.bin", preface + frame)


def gen_connect_no_path():
    # CONNECT has no ":path"; nxt_h2p_request_headers_done() answers 405,
    # not 400, for exactly this method.
    conn = client()
    conn.send_headers(1, [
        (":method", "CONNECT"),
        (":authority", "example.com:443"),
    ], end_stream=True)
    save("connect_no_path.bin", strip_preface(conn.data_to_send()))


