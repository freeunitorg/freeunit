def gen_data_before_headers():
    # DATA for a stream that never got a HEADERS: nghttp2 answers this
    # itself, but it drives nxt_h2p_on_data_chunk_recv() with stream ==
    # NULL, which is exactly the branch that must not touch stream->r.
    frame = raw_frame(0x0, 0x1, 1, b"orphan data")
    save("data_before_headers.bin", frame)


def gen_two_requests_second_bad_path():
    # A good request followed by one with a bad ":path" on the next
    # stream -- checks that per-stream error handling for one stream does
    # not disturb another already in flight on the same connection.
    import hpack

    conn = client()
    conn.send_headers(1, [
        (":method", "GET"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "/ok"),
    ], end_stream=True)
    data = strip_preface(conn.data_to_send())

    encoder = hpack.Encoder()
    block = encoder.encode([
        (":method", "GET"),
        (":scheme", "https"),
        (":authority", "example.com"),
        (":path", "nope"),
    ])
    data += raw_frame(0x1, 0x5, 3, block)
    save("two_requests_second_bad_path.bin", data)


